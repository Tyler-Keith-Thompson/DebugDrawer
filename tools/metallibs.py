#!/usr/bin/env python3
"""Precompiles each module's Metal shaders into Swift sources: `just metallibs`.

A module's shaders live in `Sources/<Module>/Shaders/<Name>.metal`. SwiftUI's `ShaderLibrary(data:)`
takes a compiled Metal library, and compiling one needs Xcode's Metal toolchain, a separate
download that neither SwiftPM nor Bazel can count on (and that every app depending on the package
would need too). So the library is compiled here, once per platform the module builds for
(scripts/modules.py), and written as raw DEFLATE in base64 into
`Sources/<Module>/<Name>Shader+<family>Library.swift`, one file per platform family, each under
`#if DEBUG`, so a release build carries none of it. Each file records the SHA-256 of the source it
was compiled from; //tools:metallibs_test fails when a source changed without a run of this.

Run it after editing a `.metal` file; it needs `xcodebuild -downloadComponent MetalToolchain` once.
"""

import base64
import hashlib
import os
import subprocess
import sys
import tempfile
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import modules  # noqa: E402 (the module graph, for each module's platforms and minimums)

LINE = 120


def shaders():
    """(module, Metal source path) for every shader under Sources/<Module>/Shaders."""
    found = []
    for module in sorted(os.listdir(os.path.join(ROOT, "Sources"))):
        directory = os.path.join(ROOT, "Sources", module, "Shaders")
        if os.path.isdir(directory):
            found += [(module, os.path.join(directory, f)) for f in sorted(os.listdir(directory)) if f.endswith(".metal")]
    return found


def families(module):
    """{family: [(Swift condition, SDK, Metal target triple)]}: the slices `module` builds for, by
    the platform family whose generated file holds them, most specific condition first."""
    result = {
        "macOS": [("os(macOS)", "macosx", f"air64-apple-macos{modules.MACOS_MINIMUM}")],
        "iOS": [
            ("os(iOS) && targetEnvironment(simulator)", "iphonesimulator", f"air64-apple-ios{modules.IOS_MINIMUM}-simulator"),
            ("os(iOS)", "iphoneos", f"air64-apple-ios{modules.IOS_MINIMUM}"),
        ],
    }
    if module in modules.CATALYST_MODULES:
        result["iOS"].insert(0, ("os(iOS) && targetEnvironment(macCatalyst)", "macosx", f"air64-apple-ios{modules.IOS_MINIMUM}-macabi"))
    sdks = {"visionOS": ("xros", "xrsimulator", "xros"), "tvOS": ("tvos", "appletvsimulator", "appletvos")}
    for platform, (minimum, names) in modules.EXTRA_PLATFORMS.items():
        if module in names and platform in sdks:
            triple, simulator, device = sdks[platform]
            result[platform] = [
                (f"os({platform}) && targetEnvironment(simulator)", simulator, f"air64-apple-{triple}{minimum}-simulator"),
                (f"os({platform})", device, f"air64-apple-{triple}{minimum}"),
            ]
    return result


def compile_library(source, sdk, target):
    """The Metal library `source` compiles to for `target`, as raw DEFLATE in base64."""
    with tempfile.TemporaryDirectory() as directory:
        output = os.path.join(directory, "shader.metallib")
        subprocess.run(["xcrun", "-sdk", sdk, "metal", "-target", target, "-o", output, source], check=True)
        with open(output, "rb") as f:
            library = f.read()
    compressor = zlib.compressobj(9, zlib.DEFLATED, -15)
    return base64.b64encode(compressor.compress(library) + compressor.flush()).decode()


def source_hash(source):
    with open(source, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def swift_file(module, source, family, slices):
    name = os.path.splitext(os.path.basename(source))[0]
    relative = os.path.relpath(source, os.path.join(ROOT, "Sources", module))
    lines = [
        f"// GENERATED by tools/metallibs.py from {relative}: edit that, then run `just metallibs`.",
        f"// Source SHA-256: {source_hash(source)}",
        "//",
        f"// The shader compiled for {family}, as raw DEFLATE in base64.",
        "",
    ]
    for index, (condition, sdk, target) in enumerate(slices):
        encoded = compile_library(source, sdk, target)
        keyword = "#if" if index == 0 else "#elseif"
        lines += [
            f"{keyword} DEBUG && {condition}",
            f"    extension {name}Shader {{",
            f"        /// The library compiled for `{target}`.",
            '        static let compressedLibrary = """',
        ]
        lines += [f"        {encoded[i:i + LINE]}" for i in range(0, len(encoded), LINE)]
        lines += ['        """', "    }"]
    lines += ["#endif", ""]
    return "\n".join(lines)


def main():
    for module, source in shaders():
        name = os.path.splitext(os.path.basename(source))[0]
        for family, slices in families(module).items():
            path = os.path.join(ROOT, "Sources", module, f"{name}Shader+{family}Library.swift")
            with open(path, "w") as f:
                f.write(swift_file(module, source, family, slices))
            print(f"wrote {os.path.relpath(path, ROOT)}")


if __name__ == "__main__":
    main()
