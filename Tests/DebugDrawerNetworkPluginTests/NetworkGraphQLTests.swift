#if DEBUG
    @testable import DebugDrawerNetworkPlugin
    import Foundation
    import Testing

    @Suite
    struct NetworkGraphQLTests {
        @Test("A POST with operationName GetUser is named GetUser, and the filter text 'GetUser' matches it")
        func operationNameInRowAndFilter() {
            let body = Data(#"{"operationName":"GetUser","query":"query GetUser($id: ID!) { user(id: $id) { name } }","variables":{"id":"1"}}"#.utf8)
            let sut = NetworkEntry(
                timestamp: Date(timeIntervalSinceReferenceDate: 800_000_000), method: "POST", url: "https://api.example.com/graphql",
                host: "api.example.com", path: "/graphql", requestHeaders: ["Content-Type": "application/json"], requestBody: body,
                statusCode: 200, isComplete: true
            )
            let other = NetworkEntry(
                timestamp: Date(timeIntervalSinceReferenceDate: 800_000_000), method: "POST", url: "https://api.example.com/graphql",
                host: "api.example.com", path: "/graphql", requestHeaders: [:], requestBody: Data(#"{"operationName":"GetPosts"}"#.utf8),
                statusCode: 200, isComplete: true
            )

            let filtered = NetworkStore.entries([sut, other], matching: .all, text: "GetUser")

            #expect(sut.graphQLOperationName == "GetUser")
            #expect(filtered.map(\.id) == [sut.id])
        }

        @Test("The filter matches the operation name ignoring case, and a part of it")
        func filterIgnoresCase() {
            let sut = NetworkEntry(
                timestamp: Date(timeIntervalSinceReferenceDate: 800_000_000), method: "POST", url: "https://api.example.com/graphql",
                host: "api.example.com", path: "/graphql", requestHeaders: [:], requestBody: Data(#"{"operationName":"UpdateUserProfile"}"#.utf8),
                isComplete: false
            )

            let actual = NetworkStore.entries([sut], matching: .all, text: "userprof")

            #expect(actual.count == 1)
        }

        @Test(
            "Without operationName, the first named operation in the query: a query, a mutation or a subscription",
            arguments: [
                (#"{"query":"query GetUser { user { name } }"}"#, "GetUser"),
                (#"{"query":"mutation UpdateUser($name: String!) { updateUser(name: $name) { id } }"}"#, "UpdateUser"),
                (#"{"query":"subscription OnMessage { message { text } }"}"#, "OnMessage"),
                (#"{"query":"query GetUser{user{name}}"}"#, "GetUser"),
                (#"{"query":"query _private_2 { a }"}"#, "_private_2")
            ]
        )
        func namedOperation(body: String, expected: String) {
            let actual = NetworkEntry.graphQLOperationName(method: "POST", url: "https://api.example.com/graphql", body: Data(body.utf8))

            #expect(actual == expected)
        }

        @Test(
            "An anonymous operation has no name",
            arguments: [#"{"query":"{ user { name } }"}"#, #"{"query":"query { user { name } }"}"#, #"{"query":"query ($id: ID) { a }"}"#]
        )
        func anonymousOperation(body: String) {
            let actual = NetworkEntry.graphQLOperationName(method: "POST", url: "https://api.example.com/graphql", body: Data(body.utf8))

            #expect(actual == nil)
        }

        @Test("An empty or non-string operationName falls back to the query's name")
        func emptyOperationNameFallsBack() {
            let empty = Data(#"{"operationName":"","query":"query FromQuery { a }"}"#.utf8)
            let number = Data(#"{"operationName":7,"query":"query FromQuery { a }"}"#.utf8)
            let null = Data(#"{"operationName":null,"query":"{ a }"}"#.utf8)

            let actual = [empty, number, null].map {
                NetworkEntry.graphQLOperationName(method: "POST", url: "https://api.example.com/graphql", body: $0)
            }

            #expect(actual == ["FromQuery", "FromQuery", nil])
        }

        @Test("Comments, commas, a byte order mark and fragments before the operation are skipped")
        func skipsCommentsAndFragments() throws {
            let query = """
            \u{FEFF}# Generated by the client
            , # a comma is ignored too
            fragment UserFields on User @include(if: true) {
              name # a } in a comment doesn't close the fragment
              bio(format: "{markdown}")
              notes(text: \"\"\"
                a block string with } and \\\""" inside
              \"\"\")
              friends { ...FriendFields }
            }
            fragment FriendFields on User { id }
            query GetUserWithFriends($id: ID!) { user(id: $id) { ...UserFields } }
            """
            let body = try JSONSerialization.data(withJSONObject: ["query": query])

            let actual = NetworkEntry.graphQLOperationName(method: "POST", url: "https://api.example.com/graphql", body: body)

            #expect(actual == "GetUserWithFriends")
        }

        @Test("A fragment that never closes, or a document of something else first, gives no name")
        func unclosedOrOther() {
            let unclosed = Data(#"{"query":"fragment F on User { name query GetUser { a }"}"#.utf8)
            let typeFirst = Data(#"{"query":"type User { id: ID } query GetUser { a }"}"#.utf8)

            let actual = [unclosed, typeFirst].map {
                NetworkEntry.graphQLOperationName(method: "POST", url: "https://api.example.com/graphql", body: $0)
            }

            #expect(actual == [nil, nil])
        }

        @Test(
            "A batch lists the first two names and how many more",
            arguments: [
                (#"[{"operationName":"A"}]"#, "A"),
                (#"[{"operationName":"A"},{"query":"query B { b }"}]"#, "A, B"),
                (#"[{"operationName":"A"},{"operationName":"B"},{"operationName":"C"},{"operationName":"D"}]"#, "A, B +2"),
                (#"[{"query":"{ a }"},{"operationName":"B"},"junk"]"#, "B")
            ]
        )
        func batches(body: String, expected: String) {
            let actual = NetworkEntry.graphQLOperationName(method: "POST", url: "https://api.example.com/graphql", body: Data(body.utf8))

            #expect(actual == expected)
        }

        @Test(
            "A batch with no named operation, an empty batch and a JSON scalar give no name",
            arguments: [#"[{"query":"{ a }"}]"#, "[]", "\"GetUser\""]
        )
        func namelessBatches(body: String) {
            let actual = NetworkEntry.graphQLOperationName(method: "POST", url: "https://api.example.com/graphql", body: Data(body.utf8))

            #expect(actual == nil)
        }

        @Test("A GET persisted query names its operation from the URL's operationName")
        func getPersistedQuery() {
            let url = "https://api.example.com/graphql?operationName=GetUser&variables=%7B%7D"
                + "&extensions=%7B%22persistedQuery%22%3A%7B%22version%22%3A1%7D%7D"

            let actual = NetworkEntry.graphQLOperationName(method: "GET", url: url, body: nil)

            #expect(actual == "GetUser")
        }

        @Test("A GET with the document in its query parameter names the operation; a search named query doesn't")
        func getQueryParameter() {
            let document = "https://api.example.com/graphql?query=query%20GetUser%20%7B%20user%20%7B%20name%20%7D%20%7D"
            let search = "https://shop.example.com/search?query=query%20shoes"

            let actual = [document, search].map { NetworkEntry.graphQLOperationName(method: "GET", url: $0, body: nil) }

            #expect(actual == ["GetUser", nil])
        }

        @Test("A body that isn't JSON gives no name", arguments: ["operationName=GetUser&query=x", "query GetUser { a }", "", "  "])
        func nonJSONBody(body: String) {
            let actual = NetworkEntry.graphQLOperationName(method: "POST", url: "https://api.example.com/graphql", body: Data(body.utf8))

            #expect(actual == nil)
        }

        @Test("A POST with no body, and a GET's JSON body, give no name")
        func noBodyAndGetBody() {
            let json = Data(#"{"operationName":"GetUser"}"#.utf8)

            let post = NetworkEntry.graphQLOperationName(method: "POST", url: "https://api.example.com/graphql", body: nil)
            let get = NetworkEntry.graphQLOperationName(method: "GET", url: "https://api.example.com/graphql", body: json)
            let put = NetworkEntry.graphQLOperationName(method: "PUT", url: "https://api.example.com/graphql", body: json)

            #expect(post == nil)
            #expect(get == nil)
            #expect(put == nil)
        }

        @Test("A lowercase method is read as the same method")
        func lowercaseMethod() {
            let actual = NetworkEntry.graphQLOperationName(
                method: "post", url: "https://api.example.com/graphql", body: Data(#"{"operationName":"GetUser"}"#.utf8)
            )

            #expect(actual == "GetUser")
        }

        @Test("A body over the limit isn't parsed; one at the limit is")
        func bodyLimit() throws {
            func body(size: Int) -> Data {
                let start = Data(#"{"operationName":"Upload","variables":{"file":""#.utf8)
                let end = Data(#""}}"#.utf8)
                return start + Data(repeating: UInt8(ascii: "a"), count: size - start.count - end.count) + end
            }
            let atLimit = body(size: NetworkEntry.graphQLBodyLimit)
            let overLimit = body(size: NetworkEntry.graphQLBodyLimit + 1)

            let actual = [atLimit, overLimit].map {
                NetworkEntry.graphQLOperationName(method: "POST", url: "https://api.example.com/graphql", body: $0)
            }

            #expect(actual == ["Upload", nil])
        }

        @Test("A name past the query's scan limit, behind a huge fragment, isn't found")
        func queryScanLimit() throws {
            let fragment = "fragment Big on User { " + String(repeating: "field ", count: NetworkEntry.graphQLQueryScanLimit / 6) + "} "
            let body = try JSONSerialization.data(withJSONObject: ["query": fragment + "query Late { a }"])

            let actual = NetworkEntry.graphQLOperationName(method: "POST", url: "https://api.example.com/graphql", body: body)

            #expect(actual == nil)
        }

        @Test("The name is worked out once, when the entry is made, from the request alone")
        func computedAtInit() {
            var sut = NetworkEntry(
                timestamp: Date(timeIntervalSinceReferenceDate: 800_000_000), method: "POST", url: "https://api.example.com/graphql",
                host: "api.example.com", path: "/graphql", requestHeaders: [:], requestBody: Data(#"{"operationName":"GetUser"}"#.utf8),
                isComplete: false
            )

            sut.responseBody = Data(#"{"operationName":"Other"}"#.utf8)
            sut.isComplete = true

            #expect(sut.graphQLOperationName == "GetUser")
        }

        @Test("An imported HAR entry names its operation from its request")
        func importedEntry() throws {
            let har = """
            {"log":{"version":"1.2","creator":{"name":"t","version":"1"},"entries":[{"startedDateTime":"2026-01-01T00:00:00Z","time":5,
            "request":{"method":"POST","url":"https://api.example.com/graphql","httpVersion":"HTTP/1.1","headers":[],"queryString":[],
            "cookies":[],"headersSize":-1,"bodySize":-1,"postData":{"mimeType":"application/json","text":"{\\"operationName\\":\\"GetCart\\"}"}},
            "response":{"status":200,"statusText":"OK","httpVersion":"HTTP/1.1","headers":[],"cookies":[],
            "content":{"size":0,"mimeType":"application/json"},"redirectURL":"","headersSize":-1,"bodySize":-1},
            "cache":{},"timings":{"send":0,"wait":5,"receive":0}}]}}
            """

            let sut = try NetworkImportedLog(fileName: "cart.har", data: Data(har.utf8))

            #expect(sut.entries.map(\.graphQLOperationName) == ["GetCart"])
        }
    }
#endif
